; ============================================================
; vga13.asm - 32-bit protected-mode graphics driver
; VGA mode 13h: 320x200, 256 colors, linear framebuffer at 0xA0000.
; ============================================================
bits 32

VGA_FB equ 0xA0000
SCR_W  equ 320
SCR_H  equ 200

clear_screen13:
    push edi
    push ecx
    mov edi, VGA_FB
    mov ecx, SCR_W * SCR_H
    rep stosb
    pop ecx
    pop edi
    ret

fill_rect:
    pushad
    mov bl, al
.next_row:
    test edx, edx
    jz .done
    mov eax, edi
    imul eax, SCR_W
    add eax, esi
    add eax, VGA_FB
    push edi
    mov edi, eax
    push ecx
    mov al, bl
    rep stosb
    pop ecx
    pop edi
    inc edi
    dec edx
    jmp .next_row
.done:
    popad
    ret

draw_char:
    pushad
    mov dh, dl
    movzx ebx, al
    sub ebx, 0x20
    js .blank
    cmp ebx, (font8x8_end - font8x8) / 8
    jae .blank
    shl ebx, 3
    add ebx, font8x8
    xor ecx, ecx
.row:
    mov ah, [ebx + ecx]
    xor ebp, ebp
.col:
    test ah, 10000000b
    jz .skip
    push eax
    mov eax, edi
    add eax, ecx
    imul eax, SCR_W
    add eax, esi
    add eax, ebp
    add eax, VGA_FB
    mov byte [eax], dh
    pop eax
.skip:
    shl ah, 1
    inc ebp
    cmp ebp, 8
    jl .col
    inc ecx
    cmp ecx, 8
    jl .row
.blank:
    popad
    ret

draw_string:
    pushad
.next:
    mov al, [ebx]
    test al, al
    jz .done
    call draw_char
    add esi, 8
    inc ebx
    jmp .next
.done:
    popad
    ret

